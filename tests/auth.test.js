import {
  createUserToken,
  hashPassword,
  publicUser,
  verifyPassword,
  verifyToken,
} from "../utils/auth.js";

describe("password hash compatibility", () => {
  it("verifies passwords generated by the supported scrypt helper", async () => {
    const hash = await hashPassword("local-test-password");

    await expect(verifyPassword("local-test-password", hash)).resolves.toBe(true);
    await expect(verifyPassword("wrong-password", hash)).resolves.toBe(false);
  });
});

describe("consumer user authentication helpers", () => {
  it("generates and verifies valid consumer user JWT tokens", () => {
    const user = { id: 123, email: "user@test.org" };
    const token = createUserToken(user);
    const decoded = verifyToken(token);

    expect(decoded.sub).toBe("123");
    expect(decoded.type).toBe("user");
    expect(decoded.email).toBe("user@test.org");
  });

  it("formats public representation of user without sensitive fields", () => {
    const row = {
      id: 1,
      name: "Alice",
      email: "alice@test.org",
      password_hash: "secret",
      status: "active",
      email_verified_at: null,
      last_login_at: null,
      created_at: "2026-01-01",
    };
    const pub = publicUser(row);
    expect(pub).not.toHaveProperty("password_hash");
    expect(pub.name).toBe("Alice");
    expect(pub.status).toBe("active");
  });
});
